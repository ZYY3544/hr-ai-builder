class QuizSubmission(BaseModel):
    answers: dict          # {题目id: 答案}  single/judge→int, multi→int 列表


def _correct(q, given) -> bool:
    if q["type"] == "multi":
        return sorted(given or []) == sorted(q["ans"])
    return given == q["ans"]


