def py_str(s: str) -> str:
    """转成 Python 双引号字符串字面量。"""
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def py_dict(d: dict) -> str:
    return '{' + ', '.join(f'{py_str(k)}: {py_str(v)}' for k, v in d.items()) + '}'


